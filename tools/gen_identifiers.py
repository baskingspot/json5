#!/usr/bin/env python3
"""Generate src/identifier_ranges.zig from UnicodeData.txt.

ECMAScript 5.1 defines IdentifierStart as `$`, `_`, or a Unicode letter in the
Lu, Ll, Lt, Lm, Lo, or Nl category. IdentifierPart adds the Mn, Mc, Nd, and Pc
categories, plus ZWNJ and ZWJ. Run this script when the pinned version changes;
`src/identifier_ranges.zig` is the committed result.

    python3 tools/gen_identifiers.py                 # download the pinned file
    python3 tools/gen_identifiers.py --data PATH     # use a local copy
"""

import argparse
import hashlib
import pathlib
import sys
import urllib.request

VERSION = "18.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt"
SHA256 = "0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950"

START_CATEGORIES = frozenset({"Lu", "Ll", "Lt", "Lm", "Lo", "Nl"})
PART_CATEGORIES = frozenset({"Mn", "Mc", "Nd", "Pc"})

# `$` and `_` are IdentifierStart by the grammar, not by category.
START_CHARS = (0x24, 0x5F)
# ZWNJ and ZWJ are IdentifierPart by the grammar, not by category.
PART_CHARS = (0x200C, 0x200D)


def read_data(path):
    if path is not None:
        data = pathlib.Path(path).read_bytes()
    else:
        data = urllib.request.urlopen(URL).read()
        digest = hashlib.sha256(data).hexdigest()
        if digest != SHA256:
            sys.exit(f"{URL}: SHA-256 is {digest}, expected {SHA256}")
    return data


def collect(data):
    start = []
    part = []
    pending = None

    def emit(first, last, category):
        if category in START_CATEGORIES:
            start.append((first, last))
            part.append((first, last))
        elif category in PART_CATEGORIES:
            part.append((first, last))

    for line in data.decode("utf-8").splitlines():
        fields = line.split(";")
        cp = int(fields[0], 16)
        name = fields[1]
        category = fields[2]
        if name.endswith(", First>"):
            pending = (cp, category)
        elif name.endswith(", Last>"):
            first, first_category = pending
            pending = None
            emit(first, cp, first_category)
        else:
            emit(cp, cp, category)

    for cp in START_CHARS:
        emit(cp, cp, "Lu")
    for cp in PART_CHARS:
        part.append((cp, cp))
    return merge(start), merge(part)


def merge(ranges):
    merged = []
    for first, last in sorted(ranges):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def render(table, ranges):
    lines = [f"pub const {table}: []const Range = &.{{"]
    for first, last in ranges:
        lines.append(f"    .{{ .first = 0x{first:04X}, .last = 0x{last:04X} }},")
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", help="a local UnicodeData.txt")
    args = parser.parse_args()

    start, part = collect(read_data(args.data))
    header = f"""//! Generated by tools/gen_identifiers.py. Do not edit.
//!
//! ECMAScript 5.1 IdentifierName ranges from Unicode {VERSION}.
//! Source: {URL}
//! SHA-256: {SHA256}
//!
//! `start` holds IdentifierStart: `$`, `_`, and the Lu, Ll, Lt, Lm, Lo, and Nl
//! categories. `part` holds IdentifierPart: everything in `start`, the Mn, Mc,
//! Nd, and Pc categories, and U+200C and U+200D.

pub const Range = struct {{
    first: u21,
    last: u21,
}};
"""
    output = "\n".join([header, render("start", start), render("part", part), ""])
    path = pathlib.Path(__file__).resolve().parent.parent / "src" / "identifier_ranges.zig"
    path.write_text(output, encoding="utf-8")
    print(f"{path}: {len(start)} start ranges, {len(part)} part ranges", file=sys.stderr)


if __name__ == "__main__":
    main()
